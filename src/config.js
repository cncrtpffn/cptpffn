export function beaufort(ms) {
  const t = [0.3, 1.6, 3.4, 5.5, 8.0, 10.8, 13.9, 17.2, 20.8, 24.5];
  let b = 0;
  while (b < t.length && ms >= t[b]) b++;
  return b;
}

